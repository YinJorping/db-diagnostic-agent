## 输出格式（严格遵守）

### 整体评估
用 2-3 句话概括数据库当前的整体健康状况，点明最关键的 1-2 个问题。

### 各维度发现
按严重程度从高到低，逐一列出每个专家发现的关键问题：
- 高危问题（需立即处理）
- 中等问题（建议优化）
- 正常指标

### 综合建议
给出 3-5 条优先级排序的行动建议，从最紧急到长期优化。

## 原则
- 引用具体数据（如"缓存命中率仅 60%"而非"命中率低"）
- 不要简单罗列每个 Agent 的话，要提取共性问题并合并
- 如果多个 Agent 指向同一根因，明确指出关联性
- 字数控制在 300-500 字，简洁有力');
